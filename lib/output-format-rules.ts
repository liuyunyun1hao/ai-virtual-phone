// 输出格式硬约束：拼在系统提示词末尾，按当前提示词里实际启用的指令动态生成。
// 放在最后是因为模型对最近的指令最敏感；只写当前用得上的条款，避免污染人设。
//
// 触发条件全部基于系统提示词里已经出现的指令名（说明这个角色本来就会用），
// 所以普通聊天不会被塞进一堆无关规则。

type Clause = { trigger: RegExp; text: string };

const CLAUSES: Clause[] = [
  {
    trigger: /\[语音条/,
    text:
      "语音条只写半角方括号 + 半角冒号：[语音条:内容]，一条独占一段。内容里的语气标注也用半角方括号（[贴近麦克风, 气声]），不要用【】［］（）。写好标注后，用户那边只会看到去掉标注的文字，听到的是带语气的声音；格式写错这条就会原样显示成普通文字。",
  },
  {
    trigger: /\[内心/,
    text:
      "[内心]…[/内心] 必须成对出现、整块独占一段，写在回复开头或结尾；中间不要再嵌 [语音条:]、[引用:] 等其它指令，也不要只写开头不写结尾。",
  },
  {
    trigger: /\[引用/,
    text:
      "[引用:原文片段] 单独一行，后面紧跟回复正文，不要用空行隔开；引用片段只抄对方原话，不要改写、不要加书名号或引号。",
  },
  {
    trigger: /双语|译文|原文\|/,
    text:
      "双语输出用半角竖线分隔：`原文|简体中文译文`，竖线两侧不留空格，一条一行；不要用｜、/、—、（）代替竖线，不要把译文另起一段，也不要翻译指令名和方括号里的参数。",
  },
  {
    trigger: /\[状态栏/,
    text:
      "[状态栏]…[/状态栏] 成对、独占一段；里面的数值行用 `字段: 值` 的半角冒号，不要写成表格或加粗。",
  },
];

/** 依据系统提示词里出现的指令，生成要追加到末尾的硬约束；没有可加的返回空串。 */
export function buildOutputFormatRule(systemText: string): string {
  const lines: string[] = [];
  CLAUSES.forEach((clause) => {
    if (!clause.trigger.test(systemText)) return;
    lines.push(`${lines.length + 1}. ${clause.text}`);
  });
  if (!lines.length) return "";
  return [
    "",
    "【输出格式 · 硬约束】以下格式比人设优先级更高，写错会导致消息无法解析或显示异常：",
    "0. 所有指令统一用半角方括号加半角冒号（[名称:内容]），不要用【】［］（）<> 包裹指令，不要写成「名称：」；指令独占一段，前后各留一个空行。",
    ...lines,
  ].join("\n");
}
