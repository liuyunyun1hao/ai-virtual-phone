const fs = require('node:fs'), ts = require('typescript'), vm = require('node:vm'), assert = require('node:assert/strict');
const source = fs.readFileSync('components/chat/share-destination-sheet.tsx','utf8');
const ast = ts.createSourceFile('sheet.tsx',source,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
const fn = ast.statements.find(n => ts.isFunctionDeclaration(n) && n.name?.text === 'canShare');
const js = ts.transpileModule(fn.getText(ast),{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText;
const canShare = vm.runInNewContext(js+';canShare',{ Date, Set, loadInteractableCharacters:()=>[{id:'a'},{id:'b'}],canCurrentIdentityInteract:id=>id!=='locked' });
assert.equal(canShare({contactId:'a'}),true);
assert.equal(canShare({contactId:'missing'}),false);
assert.equal(canShare({contactId:'a',isBlacklisted:true}),false);
assert.equal(canShare({isGroup:true,participantIds:['a','b']}),true);
assert.equal(canShare({isGroup:true,participantIds:['a','locked']}),false);
assert.equal(canShare({isGroup:true,participantIds:['a'],isSpectator:true}),false);
assert.equal(canShare({isGroup:true,participantIds:['a'],groupMutes:{self:new Date(Date.now()+60000).toISOString()}}),false);
assert.equal(canShare({isGroup:true,participantIds:['a'],groupMutes:{self:new Date(Date.now()-60000).toISOString()}}),true);
assert.equal(canShare({isGroup:true,participantIds:[]}),false);
assert.ok(source.includes('identity.current !== getCurrentIdentityId()'));
assert.ok(source.includes('if (!current || !canShare(current))'));
assert.ok(source.includes('submitting.current'));
console.log('PASS share eligibility: private/group, missing or restricted character, spectator, blacklist, mute expiry; send-time identity and duplicate guards present.');
